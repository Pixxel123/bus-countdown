def html(label, code):
    # Plain text, so labels read the same in the task editor and the Run Log (which shows labels
    # exactly as written): "Title · Explanation". Long explanations are cut to their first sentence.
    if not label:
        return label
    indent = '   ' if label.startswith('   ') else ''
    title = label.strip()
    detail = SHORT.get(title) or DETAILS.get(title, '')
    if not detail and re.search(r': (on|off)$', title):          # Profile Status steps ("Bus Moved: off")
        detail = 'Switched off and on again, so an imported profile starts listening'
    m = re.match(r'^(.*?)\s*\((.+)\)$', title)
    if not detail and m:
        title, detail = m.group(1), m.group(2)
    if len(detail) > 90 and '. ' in detail:
        detail = detail.split('. ')[0]
    detail = detail.rstrip('.')
    if detail:
        detail = detail[0].upper() + detail[1:]
    return indent + title + (' \u00b7 ' + detail if detail else '')
